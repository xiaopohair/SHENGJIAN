#!/usr/bin/env python3
"""Build the Shengjian brand SVGs and a PNG render manifest.

Usage: python brand/tools/build_assets.py
Reads:  brand/tools/wordmark-maple.json (generated by build_wordmark.ps1)
Writes: brand/logo/*.svg, brand/tools/render_manifest.json
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BRAND = ROOT / "brand"
LOGO = BRAND / "logo"
TOOLS = BRAND / "tools"

INK = "#0B0F14"
PAPER = "#F2F5F4"
TEXT = "#E9EFF7"
TEAL = "#5AC8AA"
MINT = "#8BE0C7"
DEEP = "#2E8F76"
# Light-surface brand green. Mirrors --accent under :root[data-theme="light"]
# in the desktop app, so the mark and the UI accent agree in light mode.
PINE_DEEP = "#0F7A63"
PINE_DEEP_TOP = "#1E9A7E"
PINE_DEEP_BOTTOM = "#0A5A49"
PINE_DEEP_LIP = "#08493B"

PALETTES = {
    # name: (top highlight, main, bottom)
    "teal": (MINT, TEAL, "#3FA98C"),
    "deep": (PINE_DEEP_TOP, PINE_DEEP, PINE_DEEP_BOTTOM),
}

FACE = (
    "M 24.50 14.00 L 39.50 14.00 Q 46.00 14.00 47.27 20.37 "
    "L 50.73 37.63 Q 52.00 44.00 45.50 44.00 L 18.50 44.00 "
    "Q 12.00 44.00 13.27 37.63 L 16.73 20.37 Q 18.00 14.00 24.50 14.00 Z"
)
BASE = (
    "M 24.50 17.00 L 39.50 17.00 Q 46.00 17.00 47.27 23.37 "
    "L 50.73 40.63 Q 52.00 47.00 45.50 47.00 L 18.50 47.00 "
    "Q 12.00 47.00 13.27 40.63 L 16.73 23.37 Q 18.00 17.00 24.50 17.00 Z"
)
UNION = (
    "M 24.50 14.00 L 39.50 14.00 Q 46.00 14.00 47.16 20.40 "
    "L 50.84 40.60 Q 52.00 47.00 45.50 47.00 L 18.50 47.00 "
    "Q 12.00 47.00 13.16 40.60 L 16.84 20.40 Q 18.00 14.00 24.50 14.00 Z"
)

BARS = [
    (18.0, 25.0, 7.0, 11.0),
    (28.5, 20.5, 7.0, 20.0),
    (39.0, 23.5, 7.0, 14.0),
]

VIEWBOX = "12 14 40 33"
MARK_ASPECT = 40 / 33

WM = json.loads((TOOLS / "wordmark-maple.json").read_text(encoding="utf-8-sig"))
WM_D = WM["d"]
WM_W = WM["width"]
WM_H = WM["height"]


def bar_rects() -> str:
    return "".join(
        f'      <rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{w / 2}" fill="#000"/>\n'
        for x, y, w, h in BARS
    )


def mark_defs(uid: str, mono: bool = False, palette: str = "teal") -> str:
    grad = ""
    if not mono:
        top, main, bottom = PALETTES[palette]
        grad = (
            f'    <linearGradient id="sj-{palette}-{uid}" gradientUnits="userSpaceOnUse" '
            f'x1="32" y1="14" x2="32" y2="47">\n'
            f'      <stop offset="0" stop-color="{top}"/>\n'
            f'      <stop offset="0.55" stop-color="{main}"/>\n'
            f'      <stop offset="1" stop-color="{bottom}"/>\n'
            f"    </linearGradient>\n"
        )
    return (
        "  <defs>\n"
        f"{grad}"
        f'    <mask id="sj-cut-{uid}" maskUnits="userSpaceOnUse" x="10" y="12" width="44" height="37">\n'
        f'      <path d="{UNION}" fill="#fff"/>\n'
        f"{bar_rects()}"
        "    </mask>\n"
        "  </defs>\n"
    )


def mark_content(uid: str, mono: bool = False, palette: str = "teal") -> str:
    if mono:
        return f'  <g mask="url(#sj-cut-{uid})"><path d="{UNION}" fill="currentColor"/></g>\n'
    lip = PINE_DEEP_LIP if palette == "deep" else DEEP
    return (
        f'  <g mask="url(#sj-cut-{uid})">\n'
        f'    <path d="{BASE}" fill="{lip}"/>\n'
        f'    <path d="{FACE}" fill="url(#sj-{palette}-{uid})"/>\n'
        "  </g>\n"
    )


def nested_mark(uid: str, x: float, y: float, h: float, mono: bool = False,
                fill: str | None = None, palette: str = "teal") -> str:
    w = h * MARK_ASPECT
    style = f' style="color:{fill}"' if fill else ""
    return (
        f'  <svg x="{x:g}" y="{y:g}" width="{w:.2f}" height="{h:g}" '
        f'viewBox="{VIEWBOX}"{style}>\n'
        f"{mark_defs(uid, mono, palette)}"
        f"{mark_content(uid, mono, palette)}"
        "  </svg>\n"
    )


def svg(width: float, height: float, body: str, title: str,
        root_style: str | None = None) -> str:
    w = round(width, 2)
    h = round(height, 2)
    style = f' style="{root_style}"' if root_style else ""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w:g}" height="{h:g}" '
        f'viewBox="0 0 {w:g} {h:g}"{style} role="img" aria-label="{title}">\n'
        f"  <title>{title}</title>\n"
        f"{body}"
        "</svg>\n"
    )


def write_mark() -> None:
    body = mark_defs("mark") + mark_content("mark")
    (LOGO / "shengjian-mark.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" width="200" height="165" '
        f'viewBox="{VIEWBOX}" role="img" aria-label="声键">\n'
        f"  <title>声键</title>\n{body}</svg>\n",
        encoding="utf-8",
    )
    mono_body = mark_defs("mono", mono=True) + mark_content("mono", mono=True)
    (LOGO / "shengjian-mark-mono.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" width="200" height="165" '
        f'viewBox="{VIEWBOX}" role="img" aria-label="声键（单色）">\n'
        f"  <title>声键（单色）</title>\n{mono_body}</svg>\n",
        encoding="utf-8",
    )
    ink_body = mark_defs("ink", mono=True) + mark_content("ink", mono=True)
    (LOGO / "shengjian-mark-ink.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" width="200" height="165" '
        f'viewBox="{VIEWBOX}" style="color:{INK}" role="img" aria-label="声键（墨）">\n'
        f"  <title>声键（墨）</title>\n{ink_body}</svg>\n",
        encoding="utf-8",
    )
    # Light-surface mark: same geometry, deeper green. Use on paper / light
    # sidebars / light taskbars where #5AC8AA would wash out.
    deep_body = mark_defs("onlight", palette="deep") + mark_content("onlight", palette="deep")
    (LOGO / "shengjian-mark-on-light.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" width="200" height="165" '
        f'viewBox="{VIEWBOX}" role="img" aria-label="声键（浅底）">\n'
        f"  <title>声键（浅底）</title>\n{deep_body}</svg>\n",
        encoding="utf-8",
    )


def write_wordmark() -> None:
    width = 615
    height = round(width * WM_H / WM_W, 2)
    for name, fill in (("dark", INK), ("light", TEXT)):
        text = (
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
            f'viewBox="0 0 {WM_W} {WM_H}" role="img" aria-label="声键">\n'
            f"  <title>声键</title>\n"
            f'  <path d="{WM_D}" fill="{fill}"/>\n'
            "</svg>\n"
        )
        (LOGO / f"shengjian-wordmark-{name}.svg").write_text(text, encoding="utf-8")


def lockup_horizontal(fill: str, mono: bool = False, palette: str = "teal"):
    mark_h = 96.0
    mark_w = mark_h * MARK_ASPECT
    gap = 26.0
    pad = 28.0
    wm_h = 86.0
    wm_w = WM_W * wm_h / WM_H
    total_w = pad + mark_w + gap + wm_w + pad
    total_h = pad * 2 + mark_h
    body = nested_mark("h", pad, pad, mark_h, mono=mono, palette=palette)
    wm_fill = "currentColor" if mono else fill
    body += (
        f'  <g transform="translate({pad + mark_w + gap:.2f} {pad + (mark_h - wm_h) / 2:.2f}) '
        f'scale({wm_h / WM_H:.5f})">\n'
        f'    <path d="{WM_D}" fill="{wm_fill}"/>\n'
        "  </g>\n"
    )
    root_style = f"color:{INK}" if mono else None
    return svg(total_w, total_h, body, "声键", root_style), total_w, total_h


def lockup_stacked(fill: str, mono: bool = False, palette: str = "teal"):
    mark_h = 136.0
    mark_w = mark_h * MARK_ASPECT
    wm_h = 78.0
    wm_w = WM_W * wm_h / WM_H
    gap = 24.0
    pad = 30.0
    total_w = max(mark_w, wm_w) + pad * 2
    total_h = pad + mark_h + gap + wm_h + pad
    body = nested_mark("s", (total_w - mark_w) / 2, pad, mark_h, mono=mono, palette=palette)
    wm_fill = "currentColor" if mono else fill
    body += (
        f'  <g transform="translate({(total_w - wm_w) / 2:.2f} {pad + mark_h + gap:.2f}) '
        f'scale({wm_h / WM_H:.5f})">\n'
        f'    <path d="{WM_D}" fill="{wm_fill}"/>\n'
        "  </g>\n"
    )
    root_style = f"color:{INK}" if mono else None
    return svg(total_w, total_h, body, "声键", root_style), total_w, total_h


def write_lockups() -> dict[str, tuple[float, float]]:
    sizes: dict[str, tuple[float, float]] = {}
    for name, fill, palette in (
        ("horizontal-dark", TEXT, "teal"),
        ("horizontal-light", INK, "deep"),
    ):
        text, w, h = lockup_horizontal(fill, palette=palette)
        (LOGO / f"shengjian-lockup-{name}.svg").write_text(text, encoding="utf-8")
        sizes[name] = (w, h)
    for name, fill, palette in (
        ("stacked-dark", TEXT, "teal"),
        ("stacked-light", INK, "deep"),
    ):
        text, w, h = lockup_stacked(fill, palette=palette)
        (LOGO / f"shengjian-lockup-{name}.svg").write_text(text, encoding="utf-8")
        sizes[name] = (w, h)
    # Monochrome lockups: mark and wordmark both use currentColor, so the same
    # file works for ink print, watermarks and any single-colour surface.
    for name, fn in (("horizontal-mono", lockup_horizontal), ("stacked-mono", lockup_stacked)):
        text, w, h = fn(None, mono=True)
        (LOGO / f"shengjian-lockup-{name}.svg").write_text(text, encoding="utf-8")
        sizes[name] = (w, h)
    return sizes


def write_app_icon() -> None:
    mark_h = 700.0
    mark_w = mark_h * MARK_ASPECT
    x = (1024 - mark_w) / 2
    y = (1024 - mark_h) / 2 - 8
    body = (
        '  <defs>\n'
        '    <linearGradient id="sj-bg" x1="0" y1="0" x2="0" y2="1">\n'
        '      <stop offset="0" stop-color="#141C24"/>\n'
        '      <stop offset="1" stop-color="#090D12"/>\n'
        "    </linearGradient>\n"
        '    <radialGradient id="sj-glow" cx="0.3" cy="0.16" r="0.86">\n'
        f'      <stop offset="0" stop-color="{TEAL}" stop-opacity="0.18"/>\n'
        f'      <stop offset="1" stop-color="{TEAL}" stop-opacity="0"/>\n'
        "    </radialGradient>\n"
        "  </defs>\n"
        '  <rect width="1024" height="1024" rx="230" fill="url(#sj-bg)"/>\n'
        '  <rect width="1024" height="1024" rx="230" fill="url(#sj-glow)"/>\n'
        f"{nested_mark('app', round(x, 2), round(y, 2), mark_h)}\n"
        '  <rect x="2" y="2" width="1020" height="1020" rx="228" fill="none" '
        'stroke="#ffffff" stroke-opacity="0.07" stroke-width="4"/>\n'
    )
    (LOGO / "shengjian-app-icon.svg").write_text(
        svg(1024, 1024, body, "声键"), encoding="utf-8"
    )


def write_tray() -> None:
    h = 11.2
    w = h * MARK_ASPECT
    x = (16 - w) / 2
    y = (16 - h) / 2
    for suffix, fill, palette, title in (
        ("", "#FFFFFF", "teal", "声键（托盘）"),
        ("-ink", INK, "teal", "声键（托盘·墨）"),
        ("-color", None, "teal", "声键（托盘·彩色）"),
        ("-deep", None, "deep", "声键（托盘·浅色任务栏）"),
    ):
        mono = fill is not None
        body = nested_mark(
            "tray", round(x, 2), round(y, 2), h, mono=mono, fill=fill, palette=palette
        )
        (LOGO / f"shengjian-tray-16{suffix}.svg").write_text(
            svg(16, 16, body, title), encoding="utf-8"
        )


def main() -> None:
    LOGO.mkdir(parents=True, exist_ok=True)
    write_mark()
    write_wordmark()
    lockup_sizes = write_lockups()
    write_app_icon()
    write_tray()

    jobs = []
    for size in (512, 256, 128, 64, 32, 16):
        h = round(size * 33 / 40, 2)
        jobs.append({"src": "logo/shengjian-mark.svg", "out": f"png/mark-{size}.png", "w": size, "h": h})
    for size in (128, 64):
        h = round(size * 33 / 40, 2)
        jobs.append({"src": "logo/shengjian-mark-ink.svg", "out": f"png/mark-{size}-ink.png", "w": size, "h": h})
    for size in (512, 256, 128, 64):
        h = round(size * 33 / 40, 2)
        jobs.append({"src": "logo/shengjian-mark-on-light.svg", "out": f"png/mark-{size}-on-light.png", "w": size, "h": h})
    # Stable names consumed by the Tauri host (theme-aware tray / window icons).
    jobs.append({"src": "logo/shengjian-mark-on-light.svg", "out": "png/mark-64-deep.png", "w": 64, "h": round(64 * 33 / 40, 2)})
    for size in (1024, 512, 256, 128, 64, 48, 32, 24, 16):
        jobs.append({"src": "logo/shengjian-app-icon.svg", "out": f"png/app-icon-{size}.png", "w": size, "h": size})
    for name, (w, h) in lockup_sizes.items():
        jobs.append({"src": f"logo/shengjian-lockup-{name}.svg",
                     "out": f"png/lockup-{name}-2x.png",
                     "w": round(w * 2, 2), "h": round(h * 2, 2)})
    wm_png_h = round(1230 * WM_H / WM_W, 2)
    for name in ("dark", "light"):
        jobs.append({"src": f"logo/shengjian-wordmark-{name}.svg",
                     "out": f"png/wordmark-{name}-2x.png",
                     "w": 1230, "h": wm_png_h})
    jobs.append({"src": "logo/shengjian-tray-16.svg", "out": "png/tray-16.png", "w": 16, "h": 16})
    jobs.append({"src": "logo/shengjian-tray-16.svg", "out": "png/tray-32.png", "w": 32, "h": 32})
    jobs.append({"src": "logo/shengjian-tray-16-ink.svg", "out": "png/tray-16-ink.png", "w": 16, "h": 16})
    jobs.append({"src": "logo/shengjian-tray-16-ink.svg", "out": "png/tray-32-ink.png", "w": 32, "h": 32})
    jobs.append({"src": "logo/shengjian-tray-16-color.svg", "out": "png/tray-16-color.png", "w": 16, "h": 16})
    jobs.append({"src": "logo/shengjian-tray-16-color.svg", "out": "png/tray-32-color.png", "w": 32, "h": 32})
    jobs.append({"src": "logo/shengjian-tray-16-deep.svg", "out": "png/tray-16-deep.png", "w": 16, "h": 16})
    jobs.append({"src": "logo/shengjian-tray-16-deep.svg", "out": "png/tray-32-deep.png", "w": 32, "h": 32})
    (TOOLS / "render_manifest.json").write_text(
        json.dumps(jobs, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(f"wrote logo svgs and {len(jobs)} render jobs")


if __name__ == "__main__":
    main()
