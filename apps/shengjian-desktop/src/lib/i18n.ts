export type TranslationKey = keyof typeof ENGLISH;

export function hasTranslation(source: string): source is TranslationKey {
  return source in ENGLISH;
}

export const languagePreference = computed(() => preference.value);

function resolveLocale(value: LanguagePreference): UiLocale {
  if (value === "zh-Hans" || value === "en") return value;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-Hans" : "en";
}

export const uiLocale = computed(() => resolveLocale(preference.value));

export function setLanguagePreference(value: string) {
  preference.value = value === "zh-Hans" || value === "en" ? value : "system";
  if (typeof document !== "undefined") {
    document.documentElement.lang = resolveLocale(preference.value);
  }
  if (typeof localStorage !== "undefined") {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, preference.value);
  }
}

if (typeof document !== "undefined") {
  document.documentElement.lang = resolveLocale(preference.value);
}

export function trDynamic(source: string, vars?: Record<string, string | number>): string {
  let text =
    uiLocale.value === "en" ? ((ENGLISH as Record<string, string>)[source] ?? source) : source;
  if (vars) {
    for (const [key, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${key}}`, String(value));
    }
  }
  return text;
}

export function tr(key: TranslationKey, vars?: Record<string, string | number>): string {
  return trDynamic(key, vars);
}

