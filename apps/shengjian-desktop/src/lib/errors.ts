export function localizeError(message: string, code: string | undefined, english: boolean): string {
  const table = english ? ERROR_EN : ERROR_ZH;
  const direct = table[message] ?? table[code ?? ""];
  if (direct) return direct;
  const prefix = Object.keys(table)
    .filter((key) => key.length >= 4 && message.startsWith(key))
    .sort((left, right) => right.length - left.length)[0];
  if (prefix) return message.replace(prefix, table[prefix]);
  if (/^[a-z0-9][a-z0-9_-]*$/i.test(message)) {
    return english ? "Operation failed; retry" : "操作失败，请重试";
  }
  return message;
}
